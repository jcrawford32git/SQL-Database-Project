USE MOVIECO;
DELIMITER $$

CREATE TRIGGER trg_mem_balance
AFTER UPDATE ON DETAILRENTAL
FOR EACH ROW
BEGIN
    DECLARE old_fee DECIMAL(10,2);
    DECLARE new_fee DECIMAL(10,2);
    DECLARE fee_difference DECIMAL(10,2);

    SET old_fee = IFNULL(
        GREATEST(
            DATEDIFF(OLD.DETAIL_RETURNDATE, OLD.DETAIL_DUEDATE),
            0
        ) * OLD.DETAIL_DAILYLATEFEE, 0
    );

    SET new_fee = IFNULL(
        GREATEST(
            DATEDIFF(NEW.DETAIL_RETURNDATE, NEW.DETAIL_DUEDATE),
            0
        ) * NEW.DETAIL_DAILYLATEFEE, 0
    );

    SET fee_difference = new_fee - old_fee;

    IF fee_difference <> 0 THEN
        UPDATE MEMBERSHIP
        SET MEM_BALANCE = IFNULL(MEM_BALANCE, 0)
                          + fee_difference
        WHERE MEM_NUM = (
            SELECT MEM_NUM
            FROM RENTAL
            WHERE RENT_NUM = NEW.RENT_NUM
        );
    END IF;
END$$

DELIMITER ;

