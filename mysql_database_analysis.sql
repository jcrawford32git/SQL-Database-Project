-- Question 14: Rental number generator
CREATE TABLE rent_num_seq (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY
) AUTO_INCREMENT = 1010;

DELIMITER $$

CREATE PROCEDURE prc_new_rental(IN p_mem_num DECIMAL(8,0))
BEGIN
    DECLARE member_count INT DEFAULT 0;
    DECLARE previous_balance DECIMAL(10,2);
    DECLARE new_rent_num INT;

    SELECT COUNT(*)
    INTO member_count
    FROM MEMBERSHIP
    WHERE MEM_NUM = p_mem_num;

    IF member_count = 0 THEN
        SELECT 'Membership does not exist' AS Message;
    ELSE
        SELECT MEM_BALANCE
        INTO previous_balance
        FROM MEMBERSHIP
        WHERE MEM_NUM = p_mem_num;

        SELECT CONCAT(
            'Previous balance: $ ',
            FORMAT(IFNULL(previous_balance, 0), 2)
        ) AS Message;

        INSERT INTO rent_num_seq VALUES (NULL);
        SET new_rent_num = LAST_INSERT_ID();

        INSERT INTO RENTAL (RENT_NUM, RENT_DATE, MEM_NUM)
        VALUES (new_rent_num, CURDATE(), p_mem_num);
    END IF;
END$$

DELIMITER ;

