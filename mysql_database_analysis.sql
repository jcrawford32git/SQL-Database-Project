    SELECT MAX(I2.INV_TOTAL)
    FROM LGINVOICE I2
    WHERE I2.CUST_CODE = C.CUST_CODE
)

UNION

SELECT
    C.CUST_CODE,
    C.CUST_FNAME,
    C.CUST_LNAME,
    C.CUST_STREET,
    C.CUST_CITY,
    C.CUST_STATE,
    C.CUST_ZIP,
    NULL AS INV_DATE,
    0 AS 'Largest Invoice'
FROM LGCUSTOMER C
WHERE C.CUST_STATE = 'AL'
AND NOT EXISTS (
    SELECT 1
    FROM LGINVOICE I
    WHERE I.CUST_CODE = C.CUST_CODE
)
ORDER BY CUST_LNAME, CUST_FNAME;


