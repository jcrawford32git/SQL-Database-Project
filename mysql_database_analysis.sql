SELECT
    E.EMP_NUM,
    E.EMP_FNAME,
    E.EMP_LNAME,
    E.EMP_EMAIL,
    SUM(L.LINE_QTY) AS total
FROM LGEMPLOYEE E
JOIN LGINVOICE I
    ON E.EMP_NUM = I.EMPLOYEE_ID
JOIN LGLINE L
    ON I.INV_NUM = L.INV_NUM
JOIN LGPRODUCT P
    ON L.PROD_SKU = P.PROD_SKU
JOIN LGBRAND B
    ON P.BRAND_ID = B.BRAND_ID
WHERE B.BRAND_NAME = 'BINDER PRIME'
    AND I.INV_DATE BETWEEN '2017-11-01' AND '2017-12-05'
GROUP BY E.EMP_NUM, E.EMP_FNAME, E.EMP_LNAME, E.EMP_EMAIL
HAVING SUM(L.LINE_QTY) >= ALL (
    SELECT SUM(L2.LINE_QTY)
    FROM LGINVOICE I2
    JOIN LGLINE L2
        ON I2.INV_NUM = L2.INV_NUM
    JOIN LGPRODUCT P2
        ON L2.PROD_SKU = P2.PROD_SKU
    JOIN LGBRAND B2
        ON P2.BRAND_ID = B2.BRAND_ID
    WHERE B2.BRAND_NAME = 'BINDER PRIME'
        AND I2.INV_DATE BETWEEN '2017-11-01' AND '2017-12-05'
    GROUP BY I2.EMPLOYEE_ID
)
ORDER BY E.EMP_LNAME;

